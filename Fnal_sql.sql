## task 6 customer purchase summary
use project;
select c.customer_id,c.first_name,count(distinct o.order_id) as total_orders,SUM(oi.quantity) as total_items_purchased,
sum(oi.quantity * oi.list_price) as total_revenue
from project.customers c
inner join orders o on c.customer_id = o.customer_id
inner join order_items oi
on o.order_id = oi.order_id
group by c.customer_id,c.first_name
order by total_revenue desc;
##task 7 low,high,medium
select c.customer_id,c.first_name,
sum(oi.quantity * oi.list_price) as total_spend,
    case
        when sum(oi.quantity * oi.list_price) < 5000 then 'Low'
       when sum(oi.quantity * oi.list_price) between 5000 and 15000 then 'Medium'
       else 'High'
   end as spending_category
from project.customers c
inner join project.orders o
on c.customer_id = o.customer_id
inner join project.order_items oi
on o.order_id = oi.order_id
group by c.customer_id,c.first_name
order by total_spend;
## task 8 revenue generated by each staff based on their handled orders
use project; 
select s.staff_id,s.first_name,count(distinct o.order_id) as total_orders,sum(oi.quantity* oi.list_price) as total_revenue
from project.staffs s
inner join orders o
on s.staff_id = o.staff_id
inner join  project.order_items oi
on o.order_id = oi.order_id
group by s.staff_id,s.first_name
order by total_revenue desc;
